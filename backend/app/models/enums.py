from enum import StrEnum


class LeadStatus(StrEnum):
    NEW = "new"
    CONTACTED = "contacted"
    QUALIFIED = "qualified"
    PROPOSAL_SENT = "proposal_sent"
    WON = "won"
    LOST = "lost"

    @property
    def label(self) -> str:
        """Human-readable label, e.g. `Proposal Sent` — used in system timeline entries."""
        return self.value.replace("_", " ").title()


class DiscussionKind(StrEnum):
    NOTE = "note"  # written by the sales rep
    SYSTEM = "system"  # generated by the app (lead created, status changed)
